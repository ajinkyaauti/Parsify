def generate_ats_pdf(result):
    from reportlab.lib.pagesizes import A4
    from reportlab.lib import colors
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    from reportlab.lib.units import cm

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=2*cm, bottomMargin=2*cm,
                            leftMargin=2*cm, rightMargin=2*cm)
    styles = getSampleStyleSheet()
    elements = []

    # Title
    title_style = ParagraphStyle("title", fontSize=20, fontName="Helvetica-Bold",
                                 spaceAfter=6, textColor=colors.HexColor("#1a1a18"))
    elements.append(Paragraph("ATS Resume Analysis Report", title_style))
    elements.append(Paragraph("Generated by Parsify", styles["Normal"]))
    elements.append(Spacer(1, 0.5*cm))

    # Score
    score = result.get("ats_score", 0)
    score_color = "#16a34a" if score >= 70 else "#d97706" if score >= 40 else "#dc2626"
    score_style = ParagraphStyle("score", fontSize=36, fontName="Helvetica-Bold",
                                 textColor=colors.HexColor(score_color), spaceAfter=4)
    elements.append(Paragraph(f"ATS Score: {score} / 100", score_style))

    summary = result.get("summary", "")
    if summary:
        elements.append(Paragraph(summary, styles["Normal"]))
    elements.append(Spacer(1, 0.5*cm))

    # Section scores table
    section_scores = result.get("section_scores", {})
    if section_scores:
        elements.append(Paragraph("Score Breakdown", ParagraphStyle("h2", fontSize=13,
                                  fontName="Helvetica-Bold", spaceAfter=6)))
        data = [["Category", "Score"],
                ["Skills", f"{section_scores.get('skills', 0)}%"],
                ["Experience", f"{section_scores.get('experience', 0)}%"],
                ["Education", f"{section_scores.get('education', 0)}%"]]
        t = Table(data, colWidths=[8*cm, 4*cm])
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#2563eb")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 11),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.HexColor("#f7f7f5"), colors.white]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#ddddd8")),
            ("PADDING", (0, 0), (-1, -1), 8),
        ]))
        elements.append(t)
        elements.append(Spacer(1, 0.5*cm))

    # Suggestions
    suggestions = result.get("suggestions", [])
    if suggestions:
        elements.append(Paragraph("How to Improve", ParagraphStyle("h2", fontSize=13,
                                  fontName="Helvetica-Bold", spaceAfter=6)))
        for i, s in enumerate(suggestions, 1):
            elements.append(Paragraph(f"{i}. {s}", styles["Normal"]))
            elements.append(Spacer(1, 0.2*cm))

    doc.build(elements)
    buffer.seek(0)
    return buffer.read()

