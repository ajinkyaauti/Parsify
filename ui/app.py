            suffix = os.path.splitext(resume_file.name)[1] or ".pdf"
            tmp_path = None
            try:
                with tempfile.NamedTemporaryFile(delete=False, suffix=suffix) as tmp:
                    tmp.write(resume_file.getvalue())
                    tmp_path = tmp.name
                with st.spinner("Analysing your resume with Gemini..."):
                    result = ats_scorer.score(tmp_path, jd_text, api_key=key)

                score = max(0, min(100, int(result.get("ats_score", 0) or 0)))
                if score >= 70:
                    st.success(f"### ATS Score: {score} / 100")
                elif score >= 40:
                    st.warning(f"### ATS Score: {score} / 100")
                else:
                    st.error(f"### ATS Score: {score} / 100")

                if result.get("summary"):
                    st.markdown(f"_{result['summary']}_")
                st.divider()
                section_scores = result.get("section_scores", {})
                if section_scores:
                    s1, s2, s3 = st.columns(3)
                    s1.metric("Skills", f"{section_scores.get('skills', 0)}%")
                    s2.metric("Experience", f"{section_scores.get('experience', 0)}%")
                    s3.metric("Education", f"{section_scores.get('education', 0)}%")
                st.divider()
                suggestions = result.get("suggestions", [])
                if suggestions:
                    st.markdown("**💡 How to improve**")
                    for suggestion in suggestions:
                        st.markdown(f"- {suggestion}")
                st.download_button(
                    "⬇ Download PDF Report", data=generate_ats_pdf(result),
                    file_name="ats_report.pdf", mime="application/pdf"
                )
                with st.expander("View complete analysis JSON"):
                    st.json(result)
            except Exception:
                # Avoid rendering raw provider exceptions in the UI.
                st.error("Analysis failed. Check your Gemini API key, API quota, model access, and resume file, then try again.")
            finally:
                if tmp_path and os.path.exists(tmp_path):
                    os.unlink(tmp_path)
